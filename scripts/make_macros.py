"""Write paper/results_macros.tex: one LaTeX macro per reported number, read directly from result files.

Every number quoted in the paper text is a macro defined here, so the prose cannot drift from the data.

Usage:
    python scripts/make_macros.py --results results --out paper/results_macros.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

METHOD_NAMES = {"hetero_world": "HW", "noncoop_mpc": "NonCoop", "procrustes": "Procrustes", "mappo": "MAPPO",
                "feature_sharing": "Feature", "union_select": "Union", "independent": "Indep"}
METRICS = {"deadlock_rate_pct": ("Deadlock", 1), "collision_rate_pct": ("Collision", 1),
           "completed_rate_pct": ("Completed", 1), "makespan_s": ("Makespan", 1),
           "bandwidth_kBps": ("Bandwidth", 1), "belief_w2_m": ("Wtwo", 2), "plan_disagreement_m": ("Disagree", 2),
           "alignment_w2_m": ("Align", 2), "marginal_error": ("Marginal", 3), "min_separation": ("MinSep", 2)}
NUMBER_WORDS = {2: "Two", 4: "Four", 6: "Six", 8: "Eight", 10: "Ten", 16: "Sixteen", 24: "TwentyFour",
                32: "ThirtyTwo", 40: "Forty", 50: "Fifty"}


def fmt(value: float | None, dec: int) -> str:
    """Fixed-point string, or '--' when undefined."""
    return "--" if value is None else f"{value:.{dec}f}"


def word(x: float) -> str:
    """Letters-only identifier for a numeric setting (LaTeX macro names cannot contain digits)."""
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six",
              "7": "Seven", "8": "Eight", "9": "Nine", ".": "p"}
    return "".join(digits[c] for c in f"{x:g}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--out", type=Path, default=Path("paper/results_macros.tex"))
    args = parser.parse_args()
    lines = ["% Auto-generated by scripts/make_macros.py -- do not edit by hand."]

    def emit(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    method_payloads: dict[str, dict] = {}
    for path in sorted((args.results / "main").glob("*.json")):
        payload = json.loads(path.read_text())
        method = payload["method"]
        if method in method_payloads:
            prev = method_payloads[method]
            for key, entry in payload["summary"].items():
                if not isinstance(entry, dict):
                    continue
                prev_entry = prev["summary"].setdefault(key, {})
                prev_mean = prev_entry.get("mean")
                new_mean = entry.get("mean")
                prev_n = prev_entry.get("n", 0)
                new_n = entry.get("n", 0)
                if prev_n and new_n and prev_mean is not None and new_mean is not None:
                    combined_n = prev_n + new_n
                    prev_entry["mean"] = (prev_mean * prev_n + new_mean * new_n) / combined_n
                    prev_entry["n"] = combined_n
                    prev_entry["count"] = prev_entry.get("count", 0) + entry.get("count", 0)
                    if "std" in prev_entry and "std" in entry:
                        prev_std = prev_entry["std"]
                        new_std = entry["std"]
                        if prev_std is not None and new_std is not None:
                            prev_entry["std"] = ((prev_std ** 2) * prev_n + (new_std ** 2) * new_n) / combined_n
                    if "ci95" in entry and "ci95" in prev_entry:
                        prev_entry["ci95"] = [
                            (prev_entry["ci95"][0] * prev_n + entry["ci95"][0] * new_n) / combined_n,
                            (prev_entry["ci95"][1] * prev_n + entry["ci95"][1] * new_n) / combined_n,
                        ]
                elif new_mean is not None:
                    prev_entry.update(entry)
            prev["settings"]["episodes"] = prev["settings"].get("episodes", 0) + payload["settings"].get("episodes", 0)
            prev["wall_clock_s"] = prev.get("wall_clock_s", 0.0) + payload.get("wall_clock_s", 0.0)
            continue
        method_payloads[method] = payload

    for method, payload in method_payloads.items():
        short = METHOD_NAMES[method]
        summary = payload["summary"]
        for key, (metric, dec) in METRICS.items():
            entry = summary.get(key, {})
            emit(f"res{short}{metric}", fmt(entry.get("mean"), dec))
            emit(f"res{short}{metric}Std", fmt(entry.get("std"), dec))
            if "ci95" in entry:
                emit(f"res{short}{metric}Lo", fmt(entry["ci95"][0], 1))
                emit(f"res{short}{metric}Hi", fmt(entry["ci95"][1], 1))
        emit(f"res{short}Episodes", str(payload["settings"]["episodes"]))

    latency = args.results / "latency.json"
    if latency.exists():
        data = json.loads(latency.read_text())
        for method, values in data["per_agent_latency_ms_M10"].items():
            short = METHOD_NAMES.get(method, "Pairwise")
            emit(f"lat{short}", fmt(values["mean"], 1))
            emit(f"lat{short}Std", fmt(values["std"], 1))
            emit(f"lat{short}Median", fmt(values["median"], 1))
        for row in data["scaling"]:
            tag = NUMBER_WORDS.get(row["agents"])
            if tag is None:
                continue
            for key, short in (("barycenter_joint", "BaryJoint"), ("pairwise_joint", "PairJoint"),
                               ("barycenter_fixed_dim", "BaryFixed"), ("pairwise_fixed_dim", "PairFixed"),
                               ("hetero_world_full", "HWFull"), ("union_select", "UnionSel"),
                               ("procrustes", "ProcrustesSel")):
                emit(f"scale{short}{tag}", fmt(row[key]["mean"], 1))
        for row in data["convergence"]:
            name = f"conv{word(row['epsilon'])}It{word(row['iters'])}"
            emit(f"{name}Marg", fmt(row["marginal_error"]["mean"], 3))
            emit(f"{name}Lat", fmt(row["latency_ms"]["mean"], 1))
        emit("latHardware", f"{data['hardware']['machine']} CPU ({data['hardware']['threads']} threads, "
                            f"PyTorch {data['hardware']['torch']})")

    for sub, key in (("ablation_eps", "epsilon"), ("ablation_loss", "packet_loss"), ("ablation_density", "agents")):
        for path in sorted((args.results / sub).glob("*.json")):
            payload = json.loads(path.read_text())
            short = METHOD_NAMES[payload["method"]]
            setting = word(payload["settings"][key])
            prefix = {"ablation_eps": "eps", "ablation_loss": "loss", "ablation_density": "dens"}[sub]
            for metric_key, (metric, dec) in METRICS.items():
                emit(f"{prefix}{short}{setting}{metric}", fmt(payload["summary"].get(metric_key, {}).get("mean"), dec))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} macros to {args.out}")


if __name__ == "__main__":
    main()
