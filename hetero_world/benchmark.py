"""Monte Carlo evaluation of closed-loop methods in the bottleneck corridor."""

from __future__ import annotations

import math
import time
from pathlib import Path
from typing import Callable

import torch

from .config import ConsensusConfig, CorridorConfig, PredictionConfig
from .controllers import PLAN_METHODS, Controller, NonCooperativeMPC, PlanConsensusController
from .env import BottleneckCorridorEnv

ALL_METHODS = ("hetero_world", "hw_robust", "mixture_robust", "oracle_robust", "cv_robust", "hw_anchor", "noncoop_mpc", "procrustes", "mappo", "feature_sharing", "union_select", "independent")
EVAL_SEED_BASE = 20_250_000
SEED_STRIDE = 100_000  # run seed k evaluates episodes EVAL_SEED_BASE + SEED_STRIDE * k + (0, 1, ...)


def make_controller(method: str, cfg: CorridorConfig, pcfg: PredictionConfig, ccfg: ConsensusConfig,
                    packet_loss: float = 0.0, mappo_checkpoint: str | Path | None = None,
                    belief_every: int = 4, faulty_agents: int = 0, learned: bool = False,
                    learned_scope: str = "all",
                    seed: int = 0) -> Controller:
    """Instantiate a controller by name."""
    if method in PLAN_METHODS:
        return PlanConsensusController(method, cfg, pcfg, ccfg, packet_loss=packet_loss, belief_every=belief_every,
                                       faulty_agents=faulty_agents, learned=learned, learned_scope=learned_scope,
                                       fleet_seed=seed)
    if method == "noncoop_mpc":
        return NonCooperativeMPC(cfg)
    if method == "mappo":
        from .mappo import MAPPOAgent, MAPPOController
        if mappo_checkpoint is None or not Path(mappo_checkpoint).exists():
            raise FileNotFoundError("MAPPO needs a trained checkpoint; run scripts/train_mappo.py first")
        agent = MAPPOAgent()
        agent.load_state_dict(torch.load(mappo_checkpoint, map_location="cpu")["state_dict"])
        return MAPPOController(cfg, agent)
    raise ValueError(f"unknown method {method}")


def run_episodes(controller: Controller, cfg: CorridorConfig, num_episodes: int, chunk_size: int,
                 seed_base: int = EVAL_SEED_BASE, progress: Callable[[str], None] | None = None) -> list[dict]:
    """Run ``num_episodes`` episodes in chunks and return one metrics dict per episode.

    Episode ``k`` always starts from the initial condition generated by seed ``seed_base + k``, so
    every method is evaluated on identical scenarios.
    """
    records: list[dict] = []
    for start in range(0, num_episodes, chunk_size):
        seeds = list(range(seed_base + start, seed_base + min(start + chunk_size, num_episodes)))
        env = BottleneckCorridorEnv(cfg, len(seeds))
        env.reset(seeds)
        controller.reset(env, seed=seeds[0] * 31 + 5)
        t0 = time.time()
        with torch.no_grad():
            while not bool(env.over.all()):
                controller.record_step(env)
                v_cmd, omega = controller.act(env)
                env.step(v_cmd, omega)
        metrics = env.episode_metrics()
        comm = controller.episode_stats(env)
        for b, seed in enumerate(seeds):
            row = {"seed": seed}
            for key, value in {**metrics, **comm}.items():
                row[key] = float(value[b])
            records.append(row)
        if progress is not None:
            progress(f"{controller.name}: episodes {start + len(seeds)}/{num_episodes} "
                     f"({time.time() - t0:.1f}s for chunk)")
    return records


def wilson_interval(successes: int, total: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval for a binomial proportion."""
    if total == 0:
        return float("nan"), float("nan")
    p = successes / total
    denom = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denom
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denom
    return centre - half, centre + half


def summarize(records: list[dict]) -> dict[str, dict]:
    """Aggregate per-episode records.

    Rates are reported in percent as ``mean`` with ``std`` equal to the binomial standard error and a
    95% Wilson interval. Continuous metrics report the mean and standard deviation across episodes
    (ignoring episodes where the metric is undefined).
    """
    out: dict[str, dict] = {}
    total = len(records)
    for key in ("collision", "deadlock", "completed", "collision_robot_robot", "collision_robot_human",
                "collision_human_human", "collision_wall"):
        hits = int(sum(r[key] for r in records))
        p = hits / total
        lo, hi = wilson_interval(hits, total)
        out[f"{key}_rate_pct"] = {"mean": 100 * p, "std": 100 * math.sqrt(p * (1 - p) / total),
                                  "ci95": [100 * lo, 100 * hi], "n": total, "count": hits}
    continuous = ("bandwidth_kBps", "plan_disagreement_m", "belief_w2_m", "alignment_w2_m", "marginal_error",
                  "makespan_s", "duration_s", "collision_steps", "min_separation")
    for key in continuous:
        vals = torch.tensor([r[key] for r in records], dtype=torch.float64)
        vals = vals[torch.isfinite(vals)]
        if vals.numel() == 0:
            out[key] = {"mean": None, "std": None, "n": 0}
        else:
            std = float(vals.std(unbiased=True)) if vals.numel() > 1 else 0.0
            out[key] = {"mean": float(vals.mean()), "std": std, "n": int(vals.numel())}
    return out
